# %% STEP 13: SHAP (explainer chosen automatically) -----------------------------
print("\nComputing SHAP values ...")
pre = final_pipeline[:-1]                       # imputer (+ scaler)
clf = final_pipeline.named_steps["classifier"]
X_test_t = pre.transform(X_test)
def to_3d(sv):
    """-> array (samples, features, classes) for any SHAP version"""
    return np.stack(sv, axis=-1) if isinstance(sv, list) else np.asarray(sv)

if champ_is_tree:
    shap_arr = to_3d(shap.TreeExplainer(clf).shap_values(X_test_t))
else:   # non-tree model (MLP, SVM, KNN, ...) -> model-agnostic KernelExplainer
    bg = shap.kmeans(pre.transform(X_train), 25)
    n_exp = min(40, len(X_test_t))
    ke = shap.KernelExplainer(clf.predict_proba, bg)
    shap_arr = to_3d(ke.shap_values(X_test_t[:n_exp], nsamples=150, silent=True))

mean_abs = np.abs(shap_arr).mean(axis=(0, 2))
top = np.argsort(mean_abs)[::-1][:15]
