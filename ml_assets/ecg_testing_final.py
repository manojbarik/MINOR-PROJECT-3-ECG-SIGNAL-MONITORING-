# %% STEP 16: PREDICT ON A NEW SAMPLE -------------------------------------------
LABEL_MEANINGS = {"ARR": "Arrhythmia", "AFF": "Atrial Fibrillation",
                  "CHF": "Congestive Heart Failure", "NSR": "Normal Sinus Rhythm"}

def predict_ecg_condition(feature_vector,
                          pipeline_path="ecg_final_pipeline.joblib",
                          encoder_path="ecg_label_encoder.joblib"):
    """feature_vector: the 54 feature values (WITHOUT the id and label columns)."""
    vec = np.asarray(feature_vector, dtype=float).reshape(1, -1)
    if vec.shape[1] != N_FEATURES:
        raise ValueError(f"Expected {N_FEATURES} features, got {vec.shape[1]}")
    pipe, enc = joblib.load(pipeline_path), joblib.load(encoder_path)
    proba = pipe.predict_proba(vec)[0]
    code = enc.inverse_transform([int(np.argmax(proba))])[0]
    return {"predicted_code": code,
            "predicted_condition": LABEL_MEANINGS.get(code, code),
            "confidence": float(proba.max()),
            "class_probabilities": dict(zip(enc.classes_, proba.round(4).tolist()))}

demo = predict_ecg_condition(X_test[0])
print(f"Demo -> true: {class_names[y_test[0]]} | predicted: {demo['predicted_condition']} "
      f"({demo['confidence']:.1%})")
print(demo["class_probabilities"])

